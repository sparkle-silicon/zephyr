/* ================= 对外 API ======================================== */

/**
 * @brief 使能模块时钟（MODEN0/MODEN1 读改写置位）。
 * @param moden0_mask MODEN0 位域（AE201_SYSCTL_MODEN0_x_EN），无则传 0。
 * @param moden1_mask MODEN1 位域（AE201_SYSCTL_MODEN1_x_EN），无则传 0。
 */
void ae201_sysctl_clock_enable(uint32_t moden0_mask, uint32_t moden1_mask);

/**
 * @brief 禁用模块时钟（MODEN0/MODEN1 读改写清位）。
 */
void ae201_sysctl_clock_disable(uint32_t moden0_mask, uint32_t moden1_mask);

/**
 * @brief 外设软复位 —— 置位复位（对齐固件 sysctl_mod_reset_start）。
 * @param rst0_mask RST0 位域（AE201_SYSCTL_RST0_x_RST），无则传 0。
 * @param rst1_mask RST1 位域（AE201_SYSCTL_RST1_x_RST），无则传 0。
 */
void ae201_sysctl_reset_start(uint32_t rst0_mask, uint32_t rst1_mask);

/**
 * @brief 外设软复位 —— 清位解复位（对齐固件 sysctl_mod_reset_finish）。
 */
void ae201_sysctl_reset_finish(uint32_t rst0_mask, uint32_t rst1_mask);

/**
 * @brief 外设软复位（start → finish 一次完成，含短暂空转）。
 */
void ae201_sysctl_periph_reset(uint32_t rst0_mask, uint32_t rst1_mask);

/**
 * @brief 整芯片复位（置 RST1.CHIP_RST）。复位生效后不返回。
 */
void ae201_sysctl_system_reset(void);

/**
 * @brief 写某外设时钟分频值（f = 80M / (div + 1)）。
 * @param clkdiv_offset CLKDIV 寄存器偏移（AE201_SYSCTL_CLKDIV_*_OFFSET）。
 * @param div           分频值（0 = 不分频）。
 */
void ae201_sysctl_clock_div_set(uint32_t clkdiv_offset, uint8_t div);

/**
 * @brief 读某外设时钟分频值。
 * @return 分频值 div（0 = 不分频）。
 */
uint8_t ae201_sysctl_clock_div_get(uint32_t clkdiv_offset);

/**
 * @brief 写引脚复用（PIOx_CFG，每 pin 2bit，对齐固件 sysctl_iomux_config 的寄存器布局）。
 * @param pio  物理 PIO 端口号 0~5（PIOx_CFG，每端口 16 pin）。
 * @param pin  端口内引脚号 0~15。
 * @param func 复用值 0~3（0 = GPIO 输入，1/2/3 = 外设功能，见芯片手册）。
 */
void ae201_sysctl_pio_cfg_set(uint32_t pio, uint32_t pin, uint32_t func);

